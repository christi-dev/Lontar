-- Profil pengguna (1:1 dengan auth.users milik Supabase Auth)
create table if not exists public.profiles (
  id          uuid primary key references auth.users(id) on delete cascade,
  full_name   text not null default '',
  email       text not null,
  phone       text,
  role        text not null default 'user' check (role in ('user', 'admin')),
  created_at  timestamptz not null default now()
);

-- Katalog produk
create table if not exists public.products (
  id           bigint generated by default as identity primary key,
  name         text not null,
  size         text not null default 'Reguler (22cm)',
  price        integer not null check (price >= 0),
  stock        integer not null default 0 check (stock >= 0),
  image_url    text,
  description  text not null default '',
  is_active    boolean not null default true,
  created_at   timestamptz not null default now(),
  updated_at   timestamptz not null default now()
);

-- Pesanan (header)
create table if not exists public.orders (
  id              text primary key,                -- format: ORD-XXXXXX
  user_id         uuid not null references public.profiles(id) on delete restrict,
  customer_name   text not null,
  address         text not null,
  payment_method  text not null check (payment_method in
                    ('Transfer BCA','Transfer Mandiri','Transfer BRI','QRIS','COD')),
  subtotal        integer not null check (subtotal >= 0),
  shipping_fee    integer not null default 15000 check (shipping_fee >= 0),
  total           integer not null check (total >= 0),
  status          text not null default 'Driver Menuju Toko' check (status in
                    ('Driver Menuju Toko','Driver Mengambil Pesanan','Driver Antar ke Alamat')),
  created_at      timestamptz not null default now(),
  updated_at      timestamptz not null default now()
);
create index if not exists orders_user_id_idx    on public.orders(user_id);
create index if not exists orders_created_at_idx on public.orders(created_at desc);

-- Detail item pesanan. Nama & harga disalin saat checkout (snapshot),
-- supaya riwayat pesanan tidak berubah kalau harga produk diubah nanti.
create table if not exists public.order_items (
  id            bigint generated by default as identity primary key,
  order_id      text not null references public.orders(id) on delete cascade,
  product_id    bigint references public.products(id) on delete set null,
  product_name  text not null,
  price         integer not null check (price >= 0),
  quantity      integer not null check (quantity > 0)
);
create index if not exists order_items_order_id_idx on public.order_items(order_id);

-- Notifikasi. user_id terisi = notifikasi untuk customer tsb.
-- for_admin = true            = notifikasi untuk semua admin (pesanan masuk).
create table if not exists public.notifications (
  id          bigint generated by default as identity primary key,
  user_id     uuid references public.profiles(id) on delete cascade,
  for_admin   boolean not null default false,
  text        text not null,
  is_read     boolean not null default false,
  created_at  timestamptz not null default now(),
  check (user_id is not null or for_admin)
);
create index if not exists notifications_user_idx on public.notifications(user_id, created_at desc);

-- ---------------------------------------------------------------------
-- 2. FUNGSI BANTU & TRIGGER
-- ---------------------------------------------------------------------

-- Cek apakah user yang sedang login adalah admin
create or replace function public.is_admin()
returns boolean
language sql stable security definer set search_path = public
as $$
  select exists (select 1 from public.profiles where id = auth.uid() and role = 'admin');
$$;

-- Otomatis buat baris profiles saat user mendaftar lewat Supabase Auth
create or replace function public.handle_new_user()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  insert into public.profiles (id, full_name, email)
  values (new.id, coalesce(new.raw_user_meta_data->>'full_name', ''), new.email)
  on conflict (id) do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
  after insert on auth.users
  for each row execute function public.handle_new_user();

-- Perbarui kolom updated_at otomatis
create or replace function public.touch_updated_at()
returns trigger language plpgsql as $$
begin
  new.updated_at := now();
  return new;
end;
$$;

drop trigger if exists products_touch on public.products;
create trigger products_touch before update on public.products
  for each row execute function public.touch_updated_at();

drop trigger if exists orders_touch on public.orders;
create trigger orders_touch before update on public.orders
  for each row execute function public.touch_updated_at();

-- Kirim notifikasi ke customer saat admin mengubah status pesanan
create or replace function public.notify_order_status()
returns trigger
language plpgsql security definer set search_path = public
as $$
begin
  if new.status is distinct from old.status then
    insert into public.notifications (user_id, text)
    values (new.user_id,
            format('Status pesanan %s telah diperbarui oleh Admin menjadi: "%s".', new.id, new.status));
  end if;
  return new;
end;
$$;

drop trigger if exists orders_status_notify on public.orders;
create trigger orders_status_notify after update of status on public.orders
  for each row execute function public.notify_order_status();

-- ---------------------------------------------------------------------
-- 3. CHECKOUT (RPC) — satu transaksi atomik di server
--    * Harga diambil dari tabel products (tidak percaya harga dari browser)
--    * Stok dicek & dikurangi; gagal semua jika stok kurang
--    * Membuat order + order_items + notifikasi admin
--    Dipanggil dari website: supabase.rpc('place_order', {...})
-- ---------------------------------------------------------------------
create or replace function public.place_order(
  p_items          jsonb,   -- [{ "product_id": 1, "quantity": 2 }, ...]
  p_address        text,
  p_payment_method text
)
returns public.orders
language plpgsql security definer set search_path = public
as $$
declare
  v_uid       uuid := auth.uid();
  v_profile   public.profiles;
  v_order_id  text;
  v_subtotal  integer := 0;
  v_shipping  constant integer := 15000;
  v_item      jsonb;
  v_product   public.products;
  v_qty       integer;
  v_order     public.orders;
begin
  if v_uid is null then
    raise exception 'Harap login terlebih dahulu';
  end if;

  select * into v_profile from public.profiles where id = v_uid;
  if v_profile.role = 'admin' then
    raise exception 'Akun Admin tidak dapat melakukan pembelian';
  end if;

  if p_items is null or jsonb_array_length(p_items) = 0 then
    raise exception 'Keranjang kosong';
  end if;
  if coalesce(trim(p_address), '') = '' then
    raise exception 'Alamat pengiriman wajib diisi';
  end if;

  -- ID pesanan unik, mis. ORD-4F9A2C
  loop
    v_order_id := 'ORD-' || upper(substr(md5(random()::text || clock_timestamp()::text), 1, 6));
    exit when not exists (select 1 from public.orders where id = v_order_id);
  end loop;

  insert into public.orders (id, user_id, customer_name, address, payment_method, subtotal, shipping_fee, total)
  values (v_order_id, v_uid, coalesce(nullif(v_profile.full_name, ''), v_profile.email),
          trim(p_address), p_payment_method, 0, v_shipping, 0);

  for v_item in select * from jsonb_array_elements(p_items) loop
    v_qty := (v_item->>'quantity')::integer;
    if v_qty is null or v_qty <= 0 then
      raise exception 'Jumlah produk tidak valid';
    end if;

    -- kunci baris produk agar stok aman dari pesanan bersamaan
    select * into v_product from public.products
      where id = (v_item->>'product_id')::bigint and is_active
      for update;
    if not found then
      raise exception 'Produk tidak ditemukan';
    end if;
    if v_product.stock < v_qty then
      raise exception 'Stok % tidak mencukupi (sisa %)', v_product.name, v_product.stock;
    end if;

    update public.products set stock = stock - v_qty where id = v_product.id;

    insert into public.order_items (order_id, product_id, product_name, price, quantity)
    values (v_order_id, v_product.id, v_product.name, v_product.price, v_qty);

    v_subtotal := v_subtotal + v_product.price * v_qty;
  end loop;

  update public.orders
     set subtotal = v_subtotal, total = v_subtotal + v_shipping
   where id = v_order_id
  returning * into v_order;

  insert into public.notifications (for_admin, text)
  values (true, format('Pesanan baru %s diterima dari %s (%s).',
                       v_order_id, v_order.customer_name, p_payment_method));

  return v_order;
end;
$$;

revoke all on function public.place_order(jsonb, text, text) from public, anon;
grant execute on function public.place_order(jsonb, text, text) to authenticated;

-- ---------------------------------------------------------------------
-- 4. ROW LEVEL SECURITY (RLS)
-- ---------------------------------------------------------------------
alter table public.profiles      enable row level security;
alter table public.products      enable row level security;
alter table public.orders        enable row level security;
alter table public.order_items   enable row level security;
alter table public.notifications enable row level security;

-- PROFILES
drop policy if exists "profiles: baca milik sendiri / admin" on public.profiles;
create policy "profiles: baca milik sendiri / admin" on public.profiles
  for select using (id = auth.uid() or public.is_admin());

drop policy if exists "profiles: ubah milik sendiri" on public.profiles;
create policy "profiles: ubah milik sendiri" on public.profiles
  for update using (id = auth.uid()) with check (id = auth.uid());

-- User hanya boleh mengubah nama & telepon (bukan role/email)
revoke update on public.profiles from authenticated, anon;
grant  update (full_name, phone) on public.profiles to authenticated;

-- PRODUCTS: semua orang boleh melihat produk aktif; admin kelola semuanya
drop policy if exists "products: publik lihat" on public.products;
create policy "products: publik lihat" on public.products
  for select using (is_active or public.is_admin());

drop policy if exists "products: admin kelola" on public.products;
create policy "products: admin kelola" on public.products
  for all using (public.is_admin()) with check (public.is_admin());

-- ORDERS: customer lihat miliknya; admin lihat & ubah semua.
-- Tidak ada policy INSERT → pesanan hanya bisa dibuat lewat place_order().
drop policy if exists "orders: baca milik sendiri / admin" on public.orders;
create policy "orders: baca milik sendiri / admin" on public.orders
  for select using (user_id = auth.uid() or public.is_admin());

drop policy if exists "orders: admin ubah" on public.orders;
create policy "orders: admin ubah" on public.orders
  for update using (public.is_admin()) with check (public.is_admin());

-- ORDER ITEMS
drop policy if exists "order_items: baca sesuai pesanan" on public.order_items;
create policy "order_items: baca sesuai pesanan" on public.order_items
  for select using (
    public.is_admin()
    or exists (select 1 from public.orders o where o.id = order_id and o.user_id = auth.uid())
  );

-- NOTIFICATIONS
drop policy if exists "notifications: baca" on public.notifications;
create policy "notifications: baca" on public.notifications
  for select using (user_id = auth.uid() or (for_admin and public.is_admin()));

drop policy if exists "notifications: tandai dibaca" on public.notifications;
create policy "notifications: tandai dibaca" on public.notifications
  for update using (user_id = auth.uid() or (for_admin and public.is_admin()))
  with check  (user_id = auth.uid() or (for_admin and public.is_admin()));

revoke update on public.notifications from authenticated, anon;
grant  update (is_read) on public.notifications to authenticated;

-- ---------------------------------------------------------------------
-- 5. REALTIME — tracking & notifikasi langsung ter-update tanpa refresh
-- ---------------------------------------------------------------------
do $$
begin
  begin alter publication supabase_realtime add table public.orders;        exception when duplicate_object then null; end;
  begin alter publication supabase_realtime add table public.notifications; exception when duplicate_object then null; end;
  begin alter publication supabase_realtime add table public.products;      exception when duplicate_object then null; end;
end $$;

