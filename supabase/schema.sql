insert into storage.buckets (id, name, public)
values ('product-images', 'product-images', true)
on conflict (id) do nothing;

drop policy if exists "product-images: publik lihat" on storage.objects;
create policy "product-images: publik lihat" on storage.objects
  for select using (bucket_id = 'product-images');

drop policy if exists "product-images: admin upload" on storage.objects;
create policy "product-images: admin upload" on storage.objects
  for insert with check (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "product-images: admin ubah" on storage.objects;
create policy "product-images: admin ubah" on storage.objects
  for update using (bucket_id = 'product-images' and public.is_admin());

drop policy if exists "product-images: admin hapus" on storage.objects;
create policy "product-images: admin hapus" on storage.objects
  for delete using (bucket_id = 'product-images' and public.is_admin());

